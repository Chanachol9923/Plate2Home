// Generates the provinces seed migration from data/provinces.json (single source of truth).
// Usage: node scripts/gen-provinces-sql.mjs [--check]
// --check exits non-zero if the committed migration is out of date (used by tests/CI).
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = new URL('..', import.meta.url);
const provinces = JSON.parse(readFileSync(new URL('data/provinces.json', root), 'utf8'));
const target = new URL('supabase/migrations/20260927000500_provinces_seed.sql', root);

const lit = (s) => `'${String(s).replaceAll("'", "''")}'`;
const arr = (xs) => (xs.length ? `array[${xs.map(lit).join(', ')}]` : `'{}'::text[]`);

const rows = provinces.map(
  (p, i) => `  (${lit(p.code)}, ${lit(p.name_th)}, ${lit(p.name_en)}, ${arr(p.aliases)}, ${i + 1})`,
);

export const sql = `-- GENERATED by scripts/gen-provinces-sql.mjs from data/provinces.json. Do not edit.
insert into public.provinces (code, name_th, name_en, aliases, sort_order) values
${rows.join(',\n')}
on conflict (code) do update
  set name_th = excluded.name_th,
      name_en = excluded.name_en,
      aliases = excluded.aliases,
      sort_order = excluded.sort_order;
`;

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--check')) {
    const current = readFileSync(target, 'utf8').replaceAll('\r\n', '\n');
    if (current !== sql) {
      console.error('provinces seed migration is stale: run node scripts/gen-provinces-sql.mjs');
      process.exit(1);
    }
    console.log('provinces seed migration is up to date');
  } else {
    writeFileSync(target, sql);
    console.log(`wrote ${provinces.length} provinces`);
  }
}
